package step

import (
	"context"
	"fmt"
	"strings"

	"github.com/shouni/go-veo-orchestrator/video"
)

// This file gathers the quality upkeep of video_extension (video-to-video continuation) chains:
// handing over the last frame on a chain reset, and correcting the saturation drift that builds up
// in continued generation. For the generation loop itself see video_gen.go; for the prompt and
// lastFrame choice see video_gen_prompt.go.

// applyChainResetKeyframe replaces the reference image of the new base cut after a chain reset
// with the last frame of the previous chain's actual output rather than static character art. When
// VideoProcessor is unset or the previous video's URL is empty it does nothing (generation uses the static art as before).
func (f VideoGenerationStep) applyChainResetKeyframe(ctx context.Context, sc *Context, cut *video.Cut, previousVideoURL string) error {
	if f.VideoProcessor == nil || strings.TrimSpace(previousVideoURL) == "" {
		return nil
	}
	destURI := chainFrameDestURI(sc.OutputPath, cut.CutIndex)
	if destURI == "" {
		return nil
	}
	frameURI, err := f.VideoProcessor.ExtractLastFrame(ctx, previousVideoURL, destURI)
	if err != nil {
		return fmt.Errorf("extract last frame for chain reset at cut %d: %w", cut.CutIndex, err)
	}
	cut.KeyframeReference = frameURI
	return nil
}

// chainFrameDestURI builds the destination URI of the last-frame image extracted on a chain reset.
func chainFrameDestURI(outputPath string, cutIndex int) string {
	outputPath = strings.TrimRight(strings.TrimSpace(outputPath), "/")
	if outputPath == "" {
		return ""
	}
	return fmt.Sprintf("%s/images/chain_frame_cut_%02d.png", outputPath, cutIndex)
}

// colorCorrectExtensionCut pulls the saturation of a cut just generated by video_extension
// (video-to-video continuation) back to that cut's scene keyframe image (cut.KeyframeReference).
// Veo's video_extension reuses the previous output as conditioning input, so saturation drifts and
// accumulates with every continuation (confirmed in operation: +20% saturation on the first
// continuation, with contrast rising monotonically in later rounds too). Using the corrected
// VideoURL/VideoID as the next cut's PreviousVideoURI keeps the drift from compounding into the next generation.
//
// Do not use char.ReferenceURL (the character art) as the correction reference. It is a design sheet
// of a three-view turnaround on a white background, and the white drags the whole image's average
// saturation far down (measured: SATAVG=5.2, against about 28.6 for actual scene keyframes). Using
// it as the reference actually caused a regression where the video came out unnaturally
// undersaturated (a faded look). cut.KeyframeReference is the actual scene image drawn in
// "Cinematic anime style" and carries the same colour reference used for image_to_video /
// reference_to_video generation, so that is used.
//
// When VideoProcessor is unset or the cut has no keyframe reference it does nothing
// (left uncorrected as before).
func (f VideoGenerationStep) colorCorrectExtensionCut(ctx context.Context, sc *Context, cut *video.Cut) error {
	if f.VideoProcessor == nil {
		return nil
	}
	referenceURL := strings.TrimSpace(cut.KeyframeReference)
	if referenceURL == "" {
		return nil
	}
	destURI := colorCorrectedVideoDestURI(sc.OutputPath, cut.CutIndex)
	if destURI == "" {
		return nil
	}
	correctedURI, err := f.VideoProcessor.ColorMatchSaturation(ctx, cut.VideoURL, referenceURL, destURI)
	if err != nil {
		return fmt.Errorf("color match saturation for cut %d: %w", cut.CutIndex, err)
	}
	cut.VideoURL = correctedURI
	cut.VideoID = correctedURI
	return nil
}

// colorCorrectedVideoDestURI builds the destination URI of the saturation-corrected video.
func colorCorrectedVideoDestURI(outputPath string, cutIndex int) string {
	outputPath = strings.TrimRight(strings.TrimSpace(outputPath), "/")
	if outputPath == "" {
		return ""
	}
	return fmt.Sprintf("%s/videos/cut_%02d_color_corrected.mp4", outputPath, cutIndex)
}
